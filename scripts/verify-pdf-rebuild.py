#!/usr/bin/env python3
"""Rebuild html2pdf.js from the published Corresponding Source and compare bytes.

Rebuild on Node.js 22 (the upstream .nvmrc and Clockoli CI runtime).
Only the upstream banner's year is pinned; source and dependency code are not altered.
"""
import argparse
import hashlib
from pathlib import Path, PurePosixPath
import re
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parent.parent
PREFIX = "third_party/html2pdf.js-v0.14.0/"
BUNDLE = "dist/html2pdf.bundle.min.js"
NOTICE = BUNDLE + ".LICENSE.txt"
VENDORED = "src/vendor/html2pdf.bundle.min.js"
UPSTREAM_BANNER_YEAR = b"(new Date).getFullYear()"


def require_identical(actual, expected, label):
    if actual == expected:
        return
    position = next(
        (i for i, (left, right) in enumerate(zip(actual, expected)) if left != right),
        min(len(actual), len(expected)),
    )
    digest = lambda value: hashlib.sha256(value).hexdigest()
    raise ValueError(
        f"{label} differs at byte {position}; "
        f"rebuilt={len(actual)} bytes sha256:{digest(actual)}, "
        f"pinned={len(expected)} bytes sha256:{digest(expected)}"
    )


def extract_upstream(archive, destination):
    count = 0
    for name in archive.namelist():
        if not name.startswith(PREFIX) or name.endswith("/"):
            continue
        relative = name[len(PREFIX):]
        parts = PurePosixPath(relative).parts
        if not parts or relative.startswith("/") or ".." in parts:
            raise ValueError("Unsafe path in source archive: " + name)
        target = destination.joinpath(*parts)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(archive.read(name))
        count += 1
    if count == 0:
        raise ValueError("Missing upstream html2pdf.js source tree")


def verify(source_zip):
    with zipfile.ZipFile(source_zip) as archive:
        upstream_bundle = archive.read(PREFIX + BUNDLE)
        upstream_notice = archive.read(PREFIX + NOTICE)
        vendored_bundle = archive.read(VENDORED)
        if upstream_bundle.count(b'Function("return this")()') != 1:
            raise ValueError("Unexpected pinned html2pdf.js MV3 patch location")
        require_identical(
            upstream_bundle.replace(b'Function("return this")()', b"{}"),
            vendored_bundle,
            "Archived upstream distribution and published Clockoli PDF bundle",
        )
        years = re.findall(rb"Copyright \(c\) (20[0-9]{2}) Erik Koopmans", upstream_notice)
        if len(years) != 1:
            raise ValueError("Unable to pin unique upstream copyright year")
        with tempfile.TemporaryDirectory(prefix="clockoli-pdf-rebuild-") as temporary:
            project = Path(temporary) / "html2pdf"
            extract_upstream(archive, project)
            config = project / "webpack.config.js"
            contents = config.read_bytes()
            if contents.count(UPSTREAM_BANNER_YEAR) != 1:
                raise ValueError("Unexpected upstream webpack copyright year expression")
            # Pin only the metadata year: upstream otherwise inserts the current year,
            # which would make rebuilt license notices differ in later years.
            config.write_bytes(contents.replace(UPSTREAM_BANNER_YEAR, years[0]))
            subprocess.run(
                ["npm", "ci", "--include=dev", "--ignore-scripts", "--no-audit", "--no-fund"],
                cwd=project, check=True,
            )
            subprocess.run(["npm", "run", "build"], cwd=project, check=True)
            rebuilt = (project / BUNDLE).read_bytes()
            require_identical(rebuilt, upstream_bundle, "Rebuilt upstream html2pdf.js bundle")
            rebuilt_notice = (project / NOTICE).read_bytes()
            require_identical(rebuilt_notice, upstream_notice, "Rebuilt upstream license report")
            patched = Path(temporary) / "clockoli-html2pdf.bundle.min.js"
            subprocess.run(
                ["node", str(ROOT / "scripts/apply-html2pdf-mv3.mjs"),
                 str(project / BUNDLE), str(patched)],
                cwd=ROOT, check=True,
            )
            require_identical(patched.read_bytes(), vendored_bundle,
                              "Rebuilt and MV3-patched Clockoli PDF bundle")
    print("Verified exact PDF rebuild from pinned npm sources and MV3 patch")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_zip", type=Path,
                        help="Matching Corresponding Source ZIP generated by package-source.py")
    args = parser.parse_args()
    verify(args.source_zip)
