import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const repository = resolve(root, '../..');
const vendor = await readFile(resolve(root, 'vendor/timeline-component.js'), 'utf8');
const adapter = await readFile(resolve(root, 'src/clockoli-adapter.js'), 'utf8');
const banner = '/* Vendored TaskTimeline + Clockoli adapter. Generated by packages/task-timeline-component/scripts/build.mjs. */\n';
await writeFile(resolve(repository, 'src/content/task-timeline-component.js'), `${banner}${vendor.trimEnd()}\n${adapter.trim()}\n`);
